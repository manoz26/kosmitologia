/* ── Παράγωγες δομές & βοηθητικές συναρτήσεις ───────────────────────────── */

export function getCoursesBySemester(semester: 1 | 2 | 3) {
  return courses.filter((c) => c.semester === semester);
}

export function getCoursesByTrack(track: "preparation" | "dermatology") {
  return courses.filter((c) => c.track === track);
}

/** Όλα τα μαθήματα μιας ειδίκευσης (κοινός κορμός + το ειδικό της μονοπάτι). */
export function getSpecializationCourses(spec: "preparation" | "dermatology") {
  return courses.filter((c) => c.stream === "core" || c.stream === spec);
}

export function getSpecializationEcts(spec: "preparation" | "dermatology") {
  return getSpecializationCourses(spec).reduce((sum, c) => sum + c.ects, 0);
}

export interface CurriculumRow {
  semester: 1 | 2 | 3;
  /** Κοινά μαθήματα του εξαμήνου. */
  shared: Course[];
  /** Το ζεύγος μαθημάτων που διαφοροποιεί τις δύο ειδικεύσεις (αν υπάρχει). */
  fork?: { preparation: Course; dermatology: Course };
}

/** Το πρόγραμμα δομημένο ανά εξάμηνο, με κοινά μαθήματα και σημεία διακλάδωσης. */
export const curriculum: CurriculumRow[] = semesters.map((sem) => {
  const inSemester = courses.filter((c) => c.semester === sem.id);
  const shared = inSemester.filter((c) => c.stream === "core");
  const preparation = inSemester.find((c) => c.stream === "preparation");
  const dermatology = inSemester.find((c) => c.stream === "dermatology");
  return {
    semester: sem.id,
    shared,
    fork: preparation && dermatology ? { preparation, dermatology } : undefined,
  };
});
