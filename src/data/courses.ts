  semester: 1 | 2 | 3;
  /** "core" = κοινό και στις δύο ειδικεύσεις. */
  stream: Stream;
  /** Συμβατότητα: ορίζεται μόνο στα μαθήματα που διαφοροποιούν την ειδίκευση. */
